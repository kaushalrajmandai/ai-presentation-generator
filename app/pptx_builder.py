"""Builds a .pptx from a validated Deck.
Engineered to be 100% compliant with Apple Keynote, Microsoft PowerPoint, and Google Slides.
"""
import io
import re
import zipfile
from pathlib import Path

from pptx import Presentation
from pptx.util import Inches, Pt

from .schema import Deck


def _slug(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")[:40] or "deck"


def build_pptx(deck: Deck, out_dir: Path, stem: str | None = None) -> Path:
    prs = Presentation()
    # 16:9 Widescreen standard
    prs.slide_width = Inches(13.333333)
    prs.slide_height = Inches(7.5)

    title_layout = prs.slide_layouts[0]
    content_layout = prs.slide_layouts[1]

    for i, s in enumerate(deck.slides):
        if i == 0:
            slide = prs.slides.add_slide(title_layout)
            slide.shapes.title.text = deck.deck_title
            if s.bullets:
                slide.placeholders[1].text = "\n".join(s.bullets)
        else:
            slide = prs.slides.add_slide(content_layout)
            slide.shapes.title.text = s.title
            tf = slide.placeholders[1].text_frame
            tf.clear()
            for j, b in enumerate(s.bullets):
                p = tf.paragraphs[0] if j == 0 else tf.add_paragraph()
                p.text = b
                p.space_after = Pt(14)

        # Attach speaker notes
        slide.notes_slide.notes_text_frame.text = s.speaker_notes

    # Responsible-AI disclosure slide
    last = prs.slides.add_slide(content_layout)
    last.shapes.title.text = "Responsible AI Disclosure"
    msg = "Content generated by AI from the supplied brief. Review before presenting."
    if deck.unverified_claims:
        msg += "\n\nClaims to verify:\n• " + "\n• ".join(deck.unverified_claims[:5])
    last.placeholders[1].text = msg
    last.notes_slide.notes_text_frame.text = "AI-generated disclosure slide. Verify all facts before use."

    out_dir.mkdir(parents=True, exist_ok=True)
    slug = stem or _slug(deck.deck_title)
    path = out_dir / f"{slug}.pptx"

    # Post-process XML package to ensure Apple Keynote compatibility with notes
    buf = io.BytesIO()
    prs.save(buf)
    buf.seek(0)

    with zipfile.ZipFile(buf, "r") as zin:
        # Check notesMaster relationship ID
        rels_xml = zin.read("ppt/_rels/presentation.xml.rels").decode("utf-8")
        m = re.search(r'<Relationship[^>]*Id="([^"]+)"[^>]*notesMaster', rels_xml)
        notes_rid = m.group(1) if m else "rId8"

        out_buf = io.BytesIO()
        with zipfile.ZipFile(out_buf, "w", compression=zipfile.ZIP_DEFLATED) as zout:
            for item in zin.infolist():
                content = zin.read(item.filename)
                if item.filename == "ppt/presentation.xml":
                    xml_str = content.decode("utf-8")
                    # Apple Keynote requires notesMasterIdLst to be declared in presentation.xml
                    if "<p:notesMasterIdLst>" not in xml_str:
                        nm_tag = f'<p:notesMasterIdLst><p:notesMasterId r:id="{notes_rid}"/></p:notesMasterIdLst>'
                        xml_str = xml_str.replace("<p:sldSz", f"{nm_tag}<p:sldSz")
                    content = xml_str.encode("utf-8")
                zout.writestr(item, content)

    path.write_bytes(out_buf.getvalue())
    return path
